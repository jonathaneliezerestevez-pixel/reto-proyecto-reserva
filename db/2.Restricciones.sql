ALTER TABLE Restaurante
    ALTER COLUMN Identificador ADD GENERATED BY DEFAULT AS IDENTITY,
    ADD CONSTRAINT PK_Restaurante PRIMARY KEY (Identificador);

ALTER TABLE Administrador
    ALTER COLUMN Identificador ADD GENERATED BY DEFAULT AS IDENTITY,
    ALTER COLUMN Usuario TYPE VARCHAR(15),
    ALTER COLUMN Contrasena TYPE VARCHAR(60),
    ADD CONSTRAINT PK_Administrador PRIMARY KEY (Identificador);

ALTER TABLE Reserva
    ALTER COLUMN Identificador ADD GENERATED BY DEFAULT AS IDENTITY,
    ALTER COLUMN NumeroCliente TYPE VARCHAR(20),
    ADD CONSTRAINT PK_Reserva PRIMARY KEY (Identificador),
    ADD CONSTRAINT CHK_EstadoPedido
        CHECK (EstadoPedido IN ('Disponible', 'Cancelado')),
    ALTER COLUMN FechaReserva SET DEFAULT CURRENT_TIMESTAMP,
    ADD CONSTRAINT FK_Reserva_Restaurante
        FOREIGN KEY (RestauranteId) REFERENCES Restaurante (Identificador);
